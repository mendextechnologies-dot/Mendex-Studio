"""1 MHz Coupled Inductor & Transformer SPICE Subcircuit Generator.

Generates production-grade SPICE subcircuit models (.subckt) and testbenches for:
1. 3-Limb magnetically coupled core assembly with equilateral inter-limb mutual coupling.
2. High-frequency Litz wire AC resistance modeling with Dowell proximity factor at 1 MHz.
3. Non-linear soft ferrite core loss damping resistance Rp(f) representing 3F4 MnZn losses.
4. Distributed inter-turn and inter-limb parasitic capacitances (Cp, Cg).
5. LTspice / ngspice compatible testbench netlist (.cir).
"""
from __future__ import annotations

import math
from pathlib import Path
from typing import Any, Dict
from uuid import UUID

from ..service import StudioError


class SpiceSubcircuitGenerator:
    """Generates coupled SPICE subcircuits and testbenches for High-Frequency Transformers."""

    def __init__(self, studio):
        self.studio = studio

    def generate_subcircuit(
        self,
        revision_id: UUID | str,
        turns_per_limb: int = 16,
        rated_current_rms: float = 15.0,
        frequency_hz: float = 1.0e6,
    ) -> Dict[str, Any]:
        """Generates SPICE subcircuit (.subckt) and verification netlist (.cir)."""
        rev_uuid = UUID(str(revision_id))
        rev = self.studio.get_revision(rev_uuid)
        ws_dir = self.studio.workspace_path(rev)

        # 1. Magnetic Core Parameters (Ferroxcube 3F4, 16 Toroids per limb)
        # Single toroid T107/65/25
        od_m = 0.107
        id_m = 0.065
        h_m = 0.025
        le_single_m = math.pi * (od_m + id_m) / 2.0  # 0.2702 m
        ae_single_m2 = h_m * (od_m - id_m) / 2.0    # 5.25e-4 m²

        # Stack of 16 toroids per limb
        ae_stack_m2 = 16 * ae_single_m2             # 8.40e-3 m²
        mu_0 = 4.0 * math.pi * 1.0e-7
        mu_r_3f4 = 900.0                             # Initial permeability for 3F4 @ 1 MHz, 25°C

        # Inductance per limb: L = (mu_0 * mu_r * Ae * N^2) / le
        # Magnetic path length of open triad limb with air return:
        # Reluctance R_core = le / (mu * Ae); R_air = g / (mu_0 * A_air_eff)
        # For the un-yoked limb triad, AL value is approx 32.5 µH/turn²
        al_uh_per_turn2 = 32.5
        l_magnetizing_uh = al_uh_per_turn2 * (turns_per_limb ** 2) # ~8,320 µH = 8.32 mH
        l_magnetizing_h = l_magnetizing_uh * 1.0e-6

        # Inter-limb mutual coupling in equilateral triad (pitch = 207 mm, air gap = 100 mm)
        # Without magnetic yoke, coupling factor between limbs is weak to moderate
        k_mutual = 0.085  # k12 = k23 = k31

        # 2. Winding Resistances (Litz Wire: 1000 x 0.05 mm AWG 44 or 40 x 0.05 mm)
        # Turn mean length: Mandrel OD 64mm, winding through bore (length ~ 0.52 m per turn)
        turn_length_m = 0.52
        total_wire_length_m = turns_per_limb * turn_length_m # ~8.32 m per limb
        rho_copper_75c = 2.1e-8 # Ohm-m

        # Type 2 Litz: 1000 strands x 0.05 mm (Area = 1.963 mm² = 1.963e-6 m²)
        a_cu_m2 = 1.963e-6
        r_dc_per_limb = rho_copper_75c * total_wire_length_m / a_cu_m2 # ~0.089 Ohm
        # Dowell AC proximity resistance factor at 1 MHz for AWG 44 strands
        fr_1mhz = 1.102
        r_ac_1mhz = r_dc_per_limb * fr_1mhz # ~0.098 Ohm

        # 3. Core Loss Damping Resistance (Parallel Rp)
        # Volumetric core loss for 3F4 @ 1 MHz, 45 mT is ~ 280 kW/m³
        # Volume per limb = 16 * 1.418e-4 m³ = 2.27e-3 m³
        # P_core_limb = 280e3 * 2.27e-3 ≈ 48.3 W per limb (145 W total across 3 limbs)
        p_core_limb_w = 48.3
        v_rms_rated = 2.0 * math.pi * frequency_hz * l_magnetizing_h * (rated_current_rms * 0.1) # approx drive V
        # Rp = V^2 / P_core
        # Alternatively Rp = (omega * Lm) * Q_core where Q_core = 1 / tan_delta (approx 85 for 3F4 at 1 MHz)
        omega = 2.0 * math.pi * frequency_hz
        q_core = 85.0
        r_parallel_core = omega * l_magnetizing_h * q_core # ~4.44 MegaOhms

        # 4. Parasitic Capacitances
        c_inter_turn_pf = 8.5   # pF between adjacent turns
        c_ground_pf = 24.0      # pF from winding to grounded structure

        # Build SPICE Netlist (.subckt)
        subckt_content = f"""* ==============================================================================
* Mendex Studio · High-Frequency Transformer Subcircuit Model
* Component Code : HFT-000
* Topology       : 3-Limb Equilateral Triad Magnetically Coupled Inductor/Transformer
* Operating Freq : {frequency_hz / 1.0e6:.2f} MHz
* Core Material  : Ferroxcube 3F4 (48 Toroids T107/65/25 total, 16 per limb)
* Generated by   : Mendex Core Autonomous Spice Engine
* ==============================================================================
.SUBCKT HFT_000_1MHZ L1_P L1_N L2_P L2_N L3_P L3_N GND

* --- LIMB 1: Magnetizing Branch, AC Conduction & Core Damping ---
R1_AC   L1_P    L1_INT  {r_ac_1mhz:.4f}     ; Dowell AC Resistance at 1 MHz
L1_MAG  L1_INT  L1_N    {l_magnetizing_h:.6e}   ; Magnetizing Inductance ({l_magnetizing_uh:.1f} uH)
R1_CORE L1_INT  L1_N    {r_parallel_core:.2e}   ; 3F4 Core Loss Damping Resistance (Q={q_core:.0f})
C1_TURN L1_P    L1_N    {c_inter_turn_pf:.1f}p    ; Inter-turn Parasitic Capacitance
C1_GND  L1_INT  GND     {c_ground_pf:.1f}p    ; Winding to Ground Stray Capacitance

* --- LIMB 2: Magnetizing Branch, AC Conduction & Core Damping ---
R2_AC   L2_P    L2_INT  {r_ac_1mhz:.4f}
L2_MAG  L2_INT  L2_N    {l_magnetizing_h:.6e}
R2_CORE L2_INT  L2_N    {r_parallel_core:.2e}
C2_TURN L2_P    L2_N    {c_inter_turn_pf:.1f}p
C2_GND  L2_INT  GND     {c_ground_pf:.1f}p

* --- LIMB 3: Magnetizing Branch, AC Conduction & Core Damping ---
R3_AC   L3_P    L3_INT  {r_ac_1mhz:.4f}
L3_MAG  L3_INT  L3_N    {l_magnetizing_h:.6e}
R3_CORE L3_INT  L3_N    {r_parallel_core:.2e}
C3_TURN L3_P    L3_N    {c_inter_turn_pf:.1f}p
C3_GND  L3_INT  GND     {c_ground_pf:.1f}p

* --- 3-PHASE EQUILATERAL MUTUAL MAGNETIC COUPLING ---
* Symmetric spatial coupling factor (k = {k_mutual:.3f} across 207 mm center pitch)
K12 L1_MAG L2_MAG {k_mutual:.4f}
K23 L2_MAG L3_MAG {k_mutual:.4f}
K31 L3_MAG L1_MAG {k_mutual:.4f}

.ENDS HFT_000_1MHZ
"""

        # Build Testbench Netlist (.cir)
        testbench_content = f"""* HFT-000 1 MHz AC Harmonic Frequency Response Testbench
.include HFT_000_1MHZ.subckt

* Signal Sources: 3-Phase 1 MHz Excitation (120 deg phase shift)
V_L1 N_IN1 0 SINE(0 100 1MEG 0 0 0)
V_L2 N_IN2 0 SINE(0 100 1MEG 0 0 120)
V_L3 N_IN3 0 SINE(0 100 1MEG 0 0 240)

* Source impedances
R_SRC1 N_IN1 L1_P 0.1
R_SRC2 N_IN2 L2_P 0.1
R_SRC3 N_IN3 L3_P 0.1

* Load terminations
R_LOAD1 L1_N 0 50.0
R_LOAD2 L2_N 0 50.0
R_LOAD3 L3_N 0 50.0

* Device Under Test
X_HFT L1_P L1_N L2_P L2_N L3_P L3_N 0 HFT_000_1MHZ

* Analyses
.TRAN 1n 10u 0 1n
.AC DEC 50 10k 100MEG

.PROBE V(L1_P) V(L1_N) I(V_L1)
.END
"""

        # Write simulation files into workspace
        spice_dir = ws_dir / "simulations/spice"
        spice_dir.mkdir(parents=True, exist_ok=True)
        subckt_path = spice_dir / "HFT_000_1MHZ.subckt"
        cir_path = spice_dir / "HFT_000_testbench.cir"

        subckt_path.write_text(subckt_content, encoding="utf-8")
        cir_path.write_text(testbench_content, encoding="utf-8")

        return {
            "status": "GENERATED_SUCCESS",
            "files": {
                "subcircuit": str(subckt_path.relative_to(ws_dir)).replace("\\", "/"),
                "testbench": str(cir_path.relative_to(ws_dir)).replace("\\", "/"),
            },
            "parameters": {
                "operating_frequency_hz": frequency_hz,
                "turns_per_limb": turns_per_limb,
                "magnetizing_inductance_per_limb_uh": round(l_magnetizing_uh, 1),
                "inter_limb_coupling_factor_k": k_mutual,
                "dc_resistance_per_limb_ohm": round(r_dc_per_limb, 4),
                "ac_resistance_1mhz_per_limb_ohm": round(r_ac_1mhz, 4),
                "dowell_proximity_factor_fr": fr_1mhz,
                "core_damping_resistance_rp_megohm": round(r_parallel_core / 1.0e6, 2),
                "inter_turn_capacitance_pf": c_inter_turn_pf,
            }
        }
