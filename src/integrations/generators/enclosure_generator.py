"""Parametric Mechanical Enclosure & Thermal Interface Generator.

Synthesizes:
1. Headless FreeCAD Python scripts generating ISO 10303 STEP solid models
   (enclosure base, lid, and complete assembly with mounting bosses and cutouts).
2. SVG 2D mechanical dimensional drafting drawing with orthographic views.
3. Formal mechanical and thermal interface engineering specification.
"""
from __future__ import annotations

import hashlib
